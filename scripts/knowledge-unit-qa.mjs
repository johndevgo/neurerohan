import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const require = createRequire(import.meta.url);
const ts = require("typescript");
require.extensions[".ts"] = (module, file) => module._compile(ts.transpileModule(readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, file);
const { insights } = require("../src/content/insights.ts");
const { insightPractice } = require("../src/content/insight-practice.ts");
const { resources, glossaryTerms, questionGroups } = require("../src/content/knowledge.ts");
const { marketingTools } = require("../src/content/tools.ts");
const { resourceWorkflows, toolWorkflows } = require("../src/content/knowledge-workflows.ts");
const { parseCsv } = require("../src/lib/csv-preview.ts");
const { termAnchor, normalizeTermQuery } = require("../src/lib/glossary.ts");
const { readingParagraphs } = require("../src/lib/reading.ts");
const { acceptsRequestOrigin, acceptsSubmissionTime } = require("../src/lib/request-origin.ts");
const { seoRoi, adsBreakEven, metaBudget, conversionRate, funnelEconomics, campaignMetrics, buildCampaignUrl } = require("../src/lib/marketing-calculations.ts");
const equalKeys = (objects, map, label) => assert.deepEqual(objects.map((item) => item.slug).sort(), Object.keys(map).sort(), `${label}: every page has a unique authored workflow`);
equalKeys(insights, insightPractice, "Articles");
equalKeys(resources, resourceWorkflows, "Resources");
equalKeys(marketingTools, toolWorkflows, "Tools");
for (const article of insights) {
  for (const section of article.sections) for (const paragraph of section.paragraphs ?? []) assert.equal(readingParagraphs(paragraph).join(" ").replace(/\s+/g, " "), paragraph.trim().replace(/\s+/g, " "), `${article.slug}: readable paragraph breaks preserve every word`);
  assert.equal(new Set(article.sections.map((section) => section.id)).size, article.sections.length, `${article.slug}: unique section anchors`);
  assert.ok(article.sections.length >= 8, `${article.slug}: original sections plus applied depth`);
  assert.equal(new Set(article.related.map((link) => link.href)).size, article.related.length, `${article.slug}: related destinations deduplicated`);
  assert.ok(article.sources.every((source) => new URL(source.href).protocol === "https:"), `${article.slug}: source URLs`);
  assert.equal(article.dateModified, "2026-11-14", `${article.slug}: actual editorial revision date`);
}
let templateRows = 0;
for (const resource of resources) {
  const rows = parseCsv(readFileSync(resolve("public" + resource.download.href), "utf8"));
  assert.ok(rows.length > 1, `${resource.slug}: populated download`);
  assert.equal(new Set(rows[0]).size, rows[0].length, `${resource.slug}: unique column headings`);
  for (const row of rows.slice(1)) assert.equal(row.length, rows[0].length, `${resource.slug}: CSV row matches header width`);
  templateRows += rows.length - 1;
}
assert.deepEqual(parseCsv('\uFEFFA,B\r\n"a,b","two ""quotes"""\r\n"multi\nline",\r\n'), [["A", "B"], ["a,b", 'two "quotes"'], ["multi\nline", ""]]);
assert.throws(() => parseCsv('A\n"unclosed'), /Unclosed/);
assert.equal(new Set(glossaryTerms.map((term) => termAnchor(term.term))).size, glossaryTerms.length, "Unique glossary anchors");
assert.equal(normalizeTermQuery("Search Engine Optimization"), normalizeTermQuery("Search Engine Optimisation"));
assert.equal(new Set(questionGroups.flatMap((group) => group.questions.map((question) => question.question))).size, questionGroups.reduce((total, group) => total + group.questions.length, 0), "No duplicate library questions");
assert.deepEqual(adsBreakEven(500, 40, 20, 4, "leads"), { roas: 2.5, cpa: 200, cpl: 40, cpc: 1.6 });
assert.deepEqual(adsBreakEven(500, 40, 20, 4, "purchases"), { roas: 2.5, cpa: 200, cpl: null, cpc: 8 });
assert.equal(adsBreakEven(500, 0, 20, 4, "leads").roas, null);
assert.equal(adsBreakEven(500, 40, 0, 4, "leads").cpc, 0);
const seo = seoRoi(2000, 2, 2.5, 20, 500, 1000);
assert.deepEqual(seo, { conversions: 10, customers: 2, grossProfit: 1000, roi: 0 });
assert.ok(seoRoi(2000, 3, 2, 20, 500, 1000).conversions < 0, "Downside scenario is not clamped away");
assert.equal(seoRoi(2000, 2, 3, 20, 500, 0).roi, null);
assert.deepEqual(metaBudget(40, 25, 20, 30), { base: 1000, allowance: 200, planning: 1200, daily: 40 });
assert.equal(metaBudget(40, 25, 20, 0).daily, null);
assert.deepEqual(conversionRate(5000, 150, 4), { current: 3, nonConverting: 4850, scenario: 200, additional: 50 });
assert.ok(conversionRate(5000, 150, 2).additional < 0);
assert.equal(conversionRate(0, 0, 4).current, null);
assert.deepEqual(funnelEconomics(10000, 3, 20, 800, 3000), { leads: 300, customers: 60, revenue: 48000, cac: 50 });
assert.equal(funnelEconomics(10000, 0, 20, 800, 3000).cac, null);
assert.deepEqual(campaignMetrics(1000, 100000, 2500), { cpc: 0.4, cpm: 10, ctr: 2.5 });
assert.deepEqual(campaignMetrics(0, 0, 0), { cpc: null, cpm: null, ctr: null });
const utm = { utm_source: "google", utm_medium: "cpc", utm_campaign: "new campaign", utm_term: "", utm_content: "" };
const generated = new URL(buildCampaignUrl("https://example.com/page?keep=1&utm_term=old#section", utm));
assert.equal(generated.hash, "#section"); assert.equal(generated.searchParams.get("keep"), "1");
assert.equal(generated.searchParams.get("utm_campaign"), "new campaign"); assert.ok(!generated.searchParams.has("utm_term"));
for (const invalid of ["javascript:alert(1)", "not-a-url", "https://name:secret@example.com"]) assert.equal(buildCampaignUrl(invalid, utm), null);
assert.equal(buildCampaignUrl("https://example.com", { ...utm, utm_source: " " }), null);
assert.ok(acceptsRequestOrigin("http://127.0.0.1:3182", "127.0.0.1:3182", "localhost:3182"), "Public preview origin accepted despite internal hostname");
assert.ok(acceptsRequestOrigin("https://neurerohan.com.np", "neurerohan.com.np", "localhost:3000"), "Canonical origin accepted behind internal routing");
assert.ok(acceptsRequestOrigin("https://preview.vercel.app", "preview.vercel.app", "localhost:3000"), "Preview origin accepted");
assert.ok(!acceptsRequestOrigin("https://other.example", "neurerohan.com.np", "localhost:3000"), "Cross-site origin rejected");
assert.ok(!acceptsRequestOrigin("null", "neurerohan.com.np", "localhost:3000"), "Opaque origin rejected");
assert.ok(!acceptsRequestOrigin("file:///tmp/page", "neurerohan.com.np", "localhost:3000"), "Non-web origin rejected");
for (const value of [undefined, null, "bad", Infinity, 0, 9999]) assert.ok(!acceptsSubmissionTime(value, 2000, 10000), `Invalid or premature submission timestamp rejected: ${value}`);
assert.ok(acceptsSubmissionTime(7000, 2000, 10000));
console.log(`PASS: ${insights.length} article workflows; ${resources.length} valid CSV previews (${templateRows} starter rows); ${marketingTools.length} tool workflows; ${glossaryTerms.length} unique terms; all calculator and URL-building fixtures.`);
